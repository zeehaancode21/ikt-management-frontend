  // "yyyy-MM", defaults to the current month — mirrors the owner's month
  // filter so employees can browse their own history by month too.
  const [historyMonth, setHistoryMonth] = useState<string>(() => format(new Date(), "yyyy-MM"));
  const [leaveLimit, setLeaveLimit] = useState<number>(DEFAULT_LEAVE_LIMIT);

  // ── Reapproval state ──────────────────────────────────────────
  const [reapprovalTarget, setReapprovalTarget] = useState<Leave | null>(null);
  const [reDateMode, setReDateMode] = useState<"single" | "range" | "half">("single");
  const [reHalfSession, setReHalfSession] = useState<"FIRST_HALF" | "SECOND_HALF">("FIRST_HALF");
  const [reFromDate, setReFromDate] = useState("");
  const [reToDate, setReToDate] = useState("");
  const [reReason, setReReason] = useState("");
  const [reLeaveType, setReLeaveType] = useState("SICK");
  const [reSubmitting, setReSubmitting] = useState(false);
  // Government holidays (loaded from the backend) — used together with
  // Saturday/Sunday to block those dates in the apply + edit forms.
  const [holidays, setHolidays] = useState<HolidayMap>({});
  const [cancelingId, setCancelingId] = useState<string | number | null>(null);

  const initialLoadDoneRef = useRef(false);
  const loadingLockRef = useRef(false);
  const modalCloseButtonRef = useRef<HTMLButtonElement>(null);

  // ── Load leaves ──────────────────────────────────────────────
  const load = useCallback(async () => {
    if (!name) return;
    if (loadingLockRef.current) return;
    loadingLockRef.current = true;
    setLoading(true);
    setError(null);
    try {
      const { data } = await api.get<Leave[]>("/leaves/employee", {
        params: { employeeName: name },
      });
      setLeaves(data);
    } catch (err) {
      setError(getErrorMessage(err));
    } finally {
      setLoading(false);
      loadingLockRef.current = false;
    }
  }, [name]);

  useEffect(() => {
    if (!initialLoadDoneRef.current) {
      initialLoadDoneRef.current = true;
      load();
    }
  }, [load]);

  // ── Government holidays ─────────────────────────────────────
  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const { data } = await api.get<{ date: string; name: string }[]>("/leaves/holidays");
        if (cancelled) return;
        const map: HolidayMap = {};
        data.forEach((h) => {
          map[String(h.date).slice(0, 10)] = h.name;
        });
        setHolidays(map);
      } catch {
        // non-fatal — weekends are still blocked, and the server re-checks holidays on submit
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  const dateIssue = (iso: string) => getDateBlockReason(iso, holidays);

  // ── Leave limit ─────────────────────────────────────────────
  const fetchLeaveLimit = useCallback(async () => {
    if (!name) return;
    try {
      const { data } = await api.get<{ leaveLimit: number }>("/leaves/leave-limit", {
        params: { employeeName: name },
        headers: { "Cache-Control": "no-cache" },
      });
      setLeaveLimit(data.leaveLimit);
    } catch {
      // non-fatal
    }
  }, [name]);

  useEffect(() => {
    fetchLeaveLimit();
  }, [fetchLeaveLimit]);

  useEffect(() => {
    const onFocus = () => fetchLeaveLimit();
    const onVisibility = () => {
      if (document.visibilityState === "visible") fetchLeaveLimit();
    };
    window.addEventListener("focus", onFocus);
    document.addEventListener("visibilitychange", onVisibility);
    return () => {
      window.removeEventListener("focus", onFocus);
      document.removeEventListener("visibilitychange", onVisibility);
    };
  }, [fetchLeaveLimit]);

  // ── Form helpers ─────────────────────────────────────────────
  const resetForm = () => {
    setFromDate("");
    setToDate("");
    setReason("");
    setLeaveType("SICK");
    setDateMode("single");
    setHalfSession("FIRST_HALF");
  };

  const validateForm = (): string | null => {
    if (!name) return "User name is required. Please log in again.";
    if (!fromDate) return "Please select a date.";
    if (dateMode === "range" && !toDate) return "Please select an end date.";
    const fromProblem = dateIssue(fromDate);
    if (fromProblem) return fromProblem;
    if (dateMode === "range") {
      const toProblem = dateIssue(toDate);
      if (toProblem) return toProblem;
    }
    if (dateMode === "range") {
      const fromDateObj = new Date(fromDate);
      const toDateObj = new Date(toDate);
      if (toDateObj < fromDateObj) return "End date cannot be before start date.";
      const days = calcDays(fromDate, toDate);
      if (days > 30) return "Leave duration cannot exceed 30 days. Please contact your manager.";
    }
    if (!reason.trim()) return "Please provide a reason for your leave.";
    if (reason.trim().length < 10) return "Reason must be at least 10 characters.";
    return null;
  };

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();
    const validationError = validateForm();
    if (validationError) {
      toast({ title: "Validation error", description: validationError, variant: "destructive" });
      return;
    }
    setSubmitting(true);
    const effectiveToDate = dateMode === "range" ? toDate : fromDate;
    const dateType = dateMode === "half" ? "HALF_DAY" : dateMode.toUpperCase();
    let days: number;
    if (dateMode === "range") days = calcWorkingDays(fromDate, toDate, holidays);
    else if (dateMode === "half") days = 0.5;
    else days = 1;
    try {
      await api.post<Leave>("/leaves/request", {
        employeeName: name,
        leaveType,
        fromDate,
        toDate: effectiveToDate,
        dateType,
        halfSession: dateMode === "half" ? halfSession : null,
        days,
        reason: reason.trim(),
      });
      toast({
        title: "Leave request submitted",
        description: "Your leave request has been submitted successfully.",
        className: "border-green-500 bg-green-500 text-white animate-success-bounce",
      });
      resetForm();
      await load();
    } catch (err) {
      toast({
        title: "Couldn't submit request",
        description: getErrorMessage(err) || "An unexpected error occurred.",
        variant: "destructive",
      });
    } finally {
      setSubmitting(false);
    }
  };

  // ── Reapproval handlers ─────────────────────────────────────
  const openReapproval = (l: Leave) => {
    setReapprovalTarget(l);
    const mode = l.dateType === "HALF_DAY" ? "half" : l.dateType === "RANGE" ? "range" : "single";
    setReDateMode(mode as "single" | "range" | "half");
    setReHalfSession((l.halfSession as "FIRST_HALF" | "SECOND_HALF") || "FIRST_HALF");
    setReFromDate(l.fromDate ? l.fromDate.slice(0, 10) : "");
    setReToDate(l.toDate ? l.toDate.slice(0, 10) : "");
    setReReason(l.reason || "");
    setReLeaveType(l.leaveType || "SICK");
  };

  const closeReapproval = () => {
    if (reSubmitting) return;
    setReapprovalTarget(null);
  };

  // Close the reapproval modal on Escape and move focus to the close button
  // when it opens, for a properly accessible dialog experience.
  useEffect(() => {
    if (!reapprovalTarget) return;
    modalCloseButtonRef.current?.focus();
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") closeReapproval();
    };
    document.addEventListener("keydown", onKeyDown);
    return () => document.removeEventListener("keydown", onKeyDown);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [reapprovalTarget]);

  // The same modal serves two cases, told apart by the leave's status:
